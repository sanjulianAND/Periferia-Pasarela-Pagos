-- PERXIA payments production target for MySQL 8.0.16+.
-- Expand-only. Exact retries are safe when the migration checksum and schema match.
-- IDs are application-generated UUID strings. Money is stored in minor units.
-- account_id deliberately has no FK: the owning accounts table belongs to the
-- existing backend and its physical name/type must be confirmed before coupling.

SET NAMES utf8mb4 COLLATE utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS catalog_versions (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  version VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  effective_from DATETIME(6) NOT NULL,
  effective_to DATETIME(6) NULL,
  published_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_catalog_versions_version (version),
  KEY ix_catalog_versions_effective (status, effective_from, effective_to),
  CONSTRAINT ck_catalog_versions_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'RETIRED')),
  CONSTRAINT ck_catalog_versions_window CHECK (effective_to IS NULL OR effective_to > effective_from),
  CONSTRAINT ck_catalog_versions_published CHECK (status <> 'PUBLISHED' OR published_at IS NOT NULL)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS products (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  code VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  kind VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'ACTIVE',
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_products_code (code),
  KEY ix_products_kind_status (kind, status),
  CONSTRAINT ck_products_kind CHECK (kind IN ('WORKER', 'CREDIT_PACKAGE')),
  CONSTRAINT ck_products_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS price_versions (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  catalog_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  product_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  cadence VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  unit_amount BIGINT UNSIGNED NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  included_credits BIGINT UNSIGNED NOT NULL DEFAULT 0,
  display_name VARCHAR(160) NOT NULL,
  metadata JSON NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_price_versions_catalog_product_cadence (catalog_version_id, product_id, cadence),
  KEY ix_price_versions_product (product_id, cadence),
  CONSTRAINT fk_price_versions_catalog FOREIGN KEY (catalog_version_id) REFERENCES catalog_versions (id),
  CONSTRAINT fk_price_versions_product FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT ck_price_versions_cadence CHECK (cadence IN ('ONE_TIME', 'WEEK', 'MONTH')),
  CONSTRAINT ck_price_versions_amount CHECK (unit_amount > 0),
  CONSTRAINT ck_price_versions_currency CHECK (currency = UPPER(currency) AND CHAR_LENGTH(currency) = 3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS orders (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  account_id VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  operation VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'CREATE_ORDER',
  idempotency_key_hash BINARY(32) NOT NULL,
  request_hash BINARY(32) NOT NULL,
  status VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  subtotal_amount BIGINT UNSIGNED NOT NULL,
  tax_amount BIGINT UNSIGNED NOT NULL DEFAULT 0,
  total_amount BIGINT UNSIGNED NOT NULL,
  expires_at DATETIME(6) NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_orders_id_account (id, account_id),
  UNIQUE KEY uq_orders_account_idempotency (account_id, operation, idempotency_key_hash),
  KEY ix_orders_account_created (account_id, created_at),
  KEY ix_orders_status_updated (status, updated_at),
  CONSTRAINT ck_orders_status CHECK (status IN ('DRAFT', 'PENDING_PAYMENT', 'PAYMENT_PROCESSING', 'ACTIVATION_PENDING', 'ACTIVE', 'FAILED', 'COMPENSATING', 'PARTIALLY_REFUNDED', 'REFUNDED', 'CANCELLED', 'EXTERNAL_SETTLEMENT')),
  CONSTRAINT ck_orders_currency CHECK (currency = UPPER(currency) AND CHAR_LENGTH(currency) = 3),
  CONSTRAINT ck_orders_totals CHECK (total_amount = subtotal_amount + tax_amount)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS order_items (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  account_id VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  order_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  price_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  product_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  cadence VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  quantity INT UNSIGNED NOT NULL,
  unit_amount_snapshot BIGINT UNSIGNED NOT NULL,
  line_amount BIGINT UNSIGNED NOT NULL,
  included_credits_snapshot BIGINT UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_order_items_id_account (id, account_id),
  UNIQUE KEY uq_order_items_order_price (order_id, price_version_id),
  KEY ix_order_items_account_order (account_id, order_id),
  KEY ix_order_items_product_cadence (product_id, cadence),
  CONSTRAINT fk_order_items_order_tenant FOREIGN KEY (order_id, account_id) REFERENCES orders (id, account_id),
  CONSTRAINT fk_order_items_price FOREIGN KEY (price_version_id) REFERENCES price_versions (id),
  CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT ck_order_items_cadence CHECK (cadence IN ('ONE_TIME', 'WEEK', 'MONTH')),
  CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
  CONSTRAINT ck_order_items_amount CHECK (unit_amount_snapshot > 0 AND line_amount = unit_amount_snapshot * quantity)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS subscriptions (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  account_id VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  provider VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  provider_subscription_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NULL,
  cadence VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  current_period_start DATETIME(6) NULL,
  current_period_end DATETIME(6) NULL,
  cancel_at_period_end BOOLEAN NOT NULL DEFAULT FALSE,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  active_slot TINYINT GENERATED ALWAYS AS (
    CASE WHEN status IN ('INCOMPLETE', 'ACTIVE', 'PAST_DUE', 'UNPAID', 'CANCEL_AT_PERIOD_END', 'PAUSED') THEN 1 ELSE NULL END
  ) STORED,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_subscriptions_id_account (id, account_id),
  UNIQUE KEY uq_subscriptions_provider_external (provider, provider_subscription_id),
  UNIQUE KEY uq_subscriptions_active_cadence (account_id, provider, currency, cadence, active_slot),
  KEY ix_subscriptions_account_status (account_id, status),
  KEY ix_subscriptions_period_end (status, current_period_end),
  CONSTRAINT ck_subscriptions_cadence CHECK (cadence IN ('WEEK', 'MONTH')),
  CONSTRAINT ck_subscriptions_status CHECK (status IN ('INCOMPLETE', 'ACTIVE', 'PAST_DUE', 'UNPAID', 'CANCEL_AT_PERIOD_END', 'CANCELLED', 'PAUSED')),
  CONSTRAINT ck_subscriptions_currency CHECK (currency = UPPER(currency) AND CHAR_LENGTH(currency) = 3),
  CONSTRAINT ck_subscriptions_period CHECK (current_period_end IS NULL OR current_period_start IS NULL OR current_period_end > current_period_start)
) ENGINE=InnoDB;

