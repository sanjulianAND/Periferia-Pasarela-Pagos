  item_type VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  expected_amount BIGINT NOT NULL DEFAULT 0,
  provider_amount BIGINT NOT NULL DEFAULT 0,
  fee_amount BIGINT NOT NULL DEFAULT 0,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  exception_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  owner VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NULL,
  resolved_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_reconciliation_items_reference (reconciliation_run_id, item_type, provider_reference),
