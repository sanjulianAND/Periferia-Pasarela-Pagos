CREATE TABLE IF NOT EXISTS reconciliation_runs (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  provider VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  cadence VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  period_start DATETIME(6) NOT NULL,
  period_end DATETIME(6) NOT NULL,
  currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  idempotency_key VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDING',
  gross_amount BIGINT NOT NULL DEFAULT 0,
  refund_amount BIGINT NOT NULL DEFAULT 0,
  fee_amount BIGINT NOT NULL DEFAULT 0,
  net_amount BIGINT NOT NULL DEFAULT 0,
  payout_amount BIGINT NOT NULL DEFAULT 0,
  exception_count INT UNSIGNED NOT NULL DEFAULT 0,
  started_at DATETIME(6) NULL,
  completed_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_reconciliation_runs_key (provider, idempotency_key),
  UNIQUE KEY uq_reconciliation_runs_period (provider, cadence, currency, period_start, period_end),
  KEY ix_reconciliation_runs_status_created (status, created_at),
  CONSTRAINT ck_reconciliation_runs_cadence CHECK (cadence IN ('WEEK', 'MONTH', 'AD_HOC')),
  CONSTRAINT ck_reconciliation_runs_status CHECK (status IN ('PENDING', 'RUNNING', 'MATCHED', 'EXCEPTION', 'FAILED')),
  CONSTRAINT ck_reconciliation_runs_period CHECK (period_end > period_start),
  CONSTRAINT ck_reconciliation_runs_currency CHECK (currency = UPPER(currency) AND CHAR_LENGTH(currency) = 3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS reconciliation_items (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  reconciliation_run_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  account_id VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NULL,
  payment_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  refund_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
